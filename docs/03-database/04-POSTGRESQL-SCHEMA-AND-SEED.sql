BEGIN;

-- =============================================================================
-- PHẦN 1: PHÂN HỆ AUTHENTICATION, RBAC & AUDIT LOG (7 BẢNG)
-- =============================================================================

-- 1. Bảng users
CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(50)  NOT NULL,
    email           VARCHAR(120) NOT NULL,
    password_hash   VARCHAR(255) NOT NULL,
    status          VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    last_login_at   TIMESTAMPTZ  NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email    UNIQUE (email),
    CONSTRAINT ck_users_status   CHECK (status IN ('ACTIVE', 'LOCKED', 'INACTIVE'))
);

-- 2. Bảng roles
CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(50)  NOT NULL,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(255) NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_roles_code UNIQUE (code)
);

-- 3. Bảng permissions
CREATE TABLE permissions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(80)  NOT NULL,
    name        VARCHAR(120) NOT NULL,
    module      VARCHAR(50)  NOT NULL,
    description VARCHAR(255) NULL,
    CONSTRAINT uq_permissions_code UNIQUE (code)
);

-- 4. Bảng trung gian user_roles
CREATE TABLE user_roles (
    user_id     BIGINT      NOT NULL,
    role_id     BIGINT      NOT NULL,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    assigned_by BIGINT      NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user        FOREIGN KEY (user_id)     REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_role        FOREIGN KEY (role_id)     REFERENCES roles (id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_roles_assigned_by FOREIGN KEY (assigned_by) REFERENCES users (id) ON DELETE SET NULL
);

-- 5. Bảng trung gian role_permissions
CREATE TABLE role_permissions (
    role_id       BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    CONSTRAINT pk_role_permissions PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_role_permissions_role       FOREIGN KEY (role_id)       REFERENCES roles (id)       ON DELETE CASCADE,
    CONSTRAINT fk_role_permissions_permission FOREIGN KEY (permission_id) REFERENCES permissions (id) ON DELETE CASCADE
);

-- 6. Bảng refresh_tokens
CREATE TABLE refresh_tokens (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL,
    token_hash      VARCHAR(128) NOT NULL,
    expires_at      TIMESTAMPTZ  NOT NULL,
    revoked_at      TIMESTAMPTZ  NULL,
    revoked_reason  VARCHAR(100) NULL,
    ip_address      VARCHAR(45)  NULL,
    user_agent      VARCHAR(255) NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- =============================================================================
-- PHẦN 2: PHÂN HỆ CƠ CẤU TỔ CHỨC & GIẢNG VIÊN (5 BẢNG)
-- =============================================================================

-- 7. Bảng faculties (Khoa đào tạo)
CREATE TABLE faculties (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(20)  NOT NULL,
    name        VARCHAR(150) NOT NULL,
    description TEXT         NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_faculties_code   UNIQUE (code),
    CONSTRAINT ck_faculties_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- 8. Bảng departments (Bộ môn trực thuộc Khoa)
CREATE TABLE departments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(20)  NOT NULL,
    name        VARCHAR(150) NOT NULL,
    faculty_id  BIGINT       NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_departments_code    UNIQUE (code),
    CONSTRAINT fk_departments_faculty FOREIGN KEY (faculty_id) REFERENCES faculties (id) ON DELETE RESTRICT,
    CONSTRAINT ck_departments_status  CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- 9. Bảng majors (Ngành đào tạo)
CREATE TABLE majors (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                   VARCHAR(20)  NOT NULL,
    name                   VARCHAR(150) NOT NULL,
    faculty_id             BIGINT       NOT NULL,
    total_credits_required INT          NOT NULL DEFAULT 150,
    status                 VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at             TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_majors_code    UNIQUE (code),
    CONSTRAINT fk_majors_faculty FOREIGN KEY (faculty_id) REFERENCES faculties (id) ON DELETE RESTRICT,
    CONSTRAINT ck_majors_credits CHECK (total_credits_required > 0),
    CONSTRAINT ck_majors_status  CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- 10. Bảng academic_classes (Lớp hành chính / niên chế)
CREATE TABLE academic_classes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(30)  NOT NULL,
    name        VARCHAR(150) NOT NULL,
    major_id    BIGINT       NOT NULL,
    cohort_year INT          NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_academic_classes_code   UNIQUE (code),
    CONSTRAINT fk_academic_classes_major  FOREIGN KEY (major_id) REFERENCES majors (id) ON DELETE RESTRICT,
    CONSTRAINT ck_academic_classes_cohort CHECK (cohort_year BETWEEN 2000 AND 2100),
    CONSTRAINT ck_academic_classes_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- 11. Bảng lecturers (Hồ sơ Giảng viên)
CREATE TABLE lecturers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL,
    lecturer_code VARCHAR(30)  NOT NULL,
    full_name     VARCHAR(120) NOT NULL,
    degree        VARCHAR(50)  NULL DEFAULT 'ThS',
    academic_rank VARCHAR(50)  NULL,
    department_id BIGINT       NOT NULL,
    phone         VARCHAR(20)  NULL,
    status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_lecturers_user_id    UNIQUE (user_id),
    CONSTRAINT uq_lecturers_code       UNIQUE (lecturer_code),
    CONSTRAINT fk_lecturers_user       FOREIGN KEY (user_id)       REFERENCES users (id)       ON DELETE RESTRICT,
    CONSTRAINT fk_lecturers_department FOREIGN KEY (department_id) REFERENCES departments (id) ON DELETE RESTRICT,
    CONSTRAINT ck_lecturers_status     CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- =============================================================================
-- PHẦN 3: PHÂN HỆ HỒ SƠ & TRẠNG THÁI SINH VIÊN (2 BẢNG)
-- =============================================================================

-- 12. Bảng students (Hồ sơ Sinh viên)
CREATE TABLE students (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL,
    student_code      VARCHAR(30)  NOT NULL,
    full_name         VARCHAR(120) NOT NULL,
    date_of_birth     DATE         NOT NULL,
    gender            VARCHAR(10)  NOT NULL,
    national_id       VARCHAR(20)  NOT NULL,
    personal_email    VARCHAR(120) NULL,
    phone             VARCHAR(20)  NULL,
    address           VARCHAR(255) NULL,
    avatar_url        VARCHAR(255) NULL,
    academic_class_id BIGINT       NOT NULL,
    major_id          BIGINT       NOT NULL,
    cohort_year       INT          NOT NULL,
    academic_status   VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_students_user_id        UNIQUE (user_id),
    CONSTRAINT uq_students_student_code   UNIQUE (student_code),
    CONSTRAINT uq_students_national_id    UNIQUE (national_id),
    CONSTRAINT fk_students_user           FOREIGN KEY (user_id)           REFERENCES users (id)            ON DELETE RESTRICT,
    CONSTRAINT fk_students_academic_class FOREIGN KEY (academic_class_id) REFERENCES academic_classes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_students_major          FOREIGN KEY (major_id)          REFERENCES majors (id)           ON DELETE RESTRICT,
    CONSTRAINT ck_students_gender         CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
    CONSTRAINT ck_students_cohort         CHECK (cohort_year BETWEEN 2000 AND 2100),
    CONSTRAINT ck_students_status         CHECK (academic_status IN ('ACTIVE', 'ON_LEAVE', 'SUSPENDED', 'GRADUATED', 'DROPPED_OUT'))
);

-- 13. Bảng student_status_history (Lịch sử trạng thái học vụ)
CREATE TABLE student_status_history (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT      NOT NULL,
    old_status VARCHAR(20) NULL,
    new_status VARCHAR(20) NOT NULL,
    reason     TEXT        NOT NULL,
    changed_by BIGINT      NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_status_history_student    FOREIGN KEY (student_id) REFERENCES students (id) ON DELETE CASCADE,
    CONSTRAINT fk_status_history_changed_by FOREIGN KEY (changed_by) REFERENCES users (id)    ON DELETE RESTRICT,
    CONSTRAINT ck_status_history_new_status CHECK (new_status IN ('ACTIVE', 'ON_LEAVE', 'SUSPENDED', 'GRADUATED', 'DROPPED_OUT'))
);

-- =============================================================================
-- PHẦN 4: PHÂN HỆ HỌC PHẦN, TIÊN QUYẾT & CHƯƠNG TRÌNH ĐÀO TẠO (5 BẢNG)
-- =============================================================================

-- 14. Bảng courses (Danh mục Học phần)
CREATE TABLE courses (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(20)  NOT NULL,
    name           VARCHAR(150) NOT NULL,
    credits        INT          NOT NULL,
    theory_hours   INT          NOT NULL DEFAULT 0,
    practice_hours INT          NOT NULL DEFAULT 0,
    department_id  BIGINT       NOT NULL,
    status         VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_courses_code       UNIQUE (code),
    CONSTRAINT fk_courses_department FOREIGN KEY (department_id) REFERENCES departments (id) ON DELETE RESTRICT,
    CONSTRAINT ck_courses_credits    CHECK (credits BETWEEN 1 AND 15),
    CONSTRAINT ck_courses_hours      CHECK (theory_hours >= 0 AND practice_hours >= 0),
    CONSTRAINT ck_courses_status     CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- 15. Bảng course_prerequisites (Điều kiện Tiên quyết & Học trước)
CREATE TABLE course_prerequisites (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id              BIGINT      NOT NULL,
    prerequisite_course_id BIGINT      NOT NULL,
    condition_type         VARCHAR(20) NOT NULL DEFAULT 'PREREQUISITE',
    created_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_course_prerequisites_pair UNIQUE (course_id, prerequisite_course_id),
    CONSTRAINT fk_prereq_course             FOREIGN KEY (course_id)              REFERENCES courses (id) ON DELETE CASCADE,
    CONSTRAINT fk_prereq_required_course    FOREIGN KEY (prerequisite_course_id) REFERENCES courses (id) ON DELETE RESTRICT,
    CONSTRAINT ck_prereq_not_self           CHECK (course_id <> prerequisite_course_id),
    CONSTRAINT ck_prereq_condition_type     CHECK (condition_type IN ('PREREQUISITE', 'COREQUISITE'))
);

-- 16. Bảng grade_components (Thành phần điểm của Học phần)
CREATE TABLE grade_components (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id      BIGINT       NOT NULL,
    code           VARCHAR(30)  NOT NULL,
    name           VARCHAR(100) NOT NULL,
    weight_percent INT          NOT NULL,
    is_final_exam  BOOLEAN      NOT NULL DEFAULT FALSE,
    min_threshold  NUMERIC(4,1) NOT NULL DEFAULT 0.0,
    display_order  INT          NOT NULL DEFAULT 1,
    CONSTRAINT uq_grade_components_course_code UNIQUE (course_id, code),
    CONSTRAINT fk_grade_components_course      FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE CASCADE,
    CONSTRAINT ck_grade_components_weight      CHECK (weight_percent > 0 AND weight_percent <= 100),
    CONSTRAINT ck_grade_components_threshold   CHECK (min_threshold BETWEEN 0.0 AND 10.0)
);

-- 17. Bảng curriculums (Chương trình đào tạo theo Ngành & Khóa)
CREATE TABLE curriculums (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(30)  NOT NULL,
    name          VARCHAR(150) NOT NULL,
    major_id      BIGINT       NOT NULL,
    cohort_year   INT          NOT NULL,
    total_credits INT          NOT NULL DEFAULT 150,
    status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_curriculums_code         UNIQUE (code),
    CONSTRAINT uq_curriculums_major_cohort UNIQUE (major_id, cohort_year),
    CONSTRAINT fk_curriculums_major        FOREIGN KEY (major_id) REFERENCES majors (id) ON DELETE RESTRICT,
    CONSTRAINT ck_curriculums_credits      CHECK (total_credits > 0),
    CONSTRAINT ck_curriculums_status       CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- 18. Bảng curriculum_courses (Học phần thuộc Chương trình đào tạo)
CREATE TABLE curriculum_courses (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curriculum_id        BIGINT  NOT NULL,
    course_id            BIGINT  NOT NULL,
    recommended_semester INT     NOT NULL,
    is_required          BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_curriculum_courses_pair     UNIQUE (curriculum_id, course_id),
    CONSTRAINT fk_curriculum_courses_curr     FOREIGN KEY (curriculum_id) REFERENCES curriculums (id) ON DELETE CASCADE,
    CONSTRAINT fk_curriculum_courses_course   FOREIGN KEY (course_id)     REFERENCES courses (id)     ON DELETE RESTRICT,
    CONSTRAINT ck_curriculum_courses_semester CHECK (recommended_semester BETWEEN 1 AND 10)
);

-- =============================================================================
-- PHẦN 5: PHÂN HỆ NIÊN LỊCH HỌC KỲ, PHÒNG HỌC, LỚP HỌC PHẦN & LỊCH HỌC (5 BẢNG)
-- =============================================================================

-- 19. Bảng academic_years (Năm học)
CREATE TABLE academic_years (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(20)  NOT NULL,
    name       VARCHAR(100) NOT NULL,
    start_year INT          NOT NULL,
    end_year   INT          NOT NULL,
    status     VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT uq_academic_years_code   UNIQUE (code),
    CONSTRAINT ck_academic_years_range  CHECK (end_year = start_year + 1),
    CONSTRAINT ck_academic_years_status CHECK (status IN ('ACTIVE', 'ARCHIVED'))
);

-- 20. Bảng semesters (Học kỳ & Cấu hình Đợt đăng ký)
CREATE TABLE semesters (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                  VARCHAR(20)  NOT NULL,
    name                  VARCHAR(100) NOT NULL,
    academic_year_id      BIGINT       NOT NULL,
    term_type             VARCHAR(20)  NOT NULL DEFAULT 'REGULAR',
    start_date            DATE         NOT NULL,
    end_date              DATE         NOT NULL,
    min_credits           INT          NOT NULL DEFAULT 12,
    max_credits           INT          NOT NULL DEFAULT 24,
    registration_start_at TIMESTAMPTZ  NOT NULL,
    registration_end_at   TIMESTAMPTZ  NOT NULL,
    is_registration_open  BOOLEAN      NOT NULL DEFAULT FALSE,
    status                VARCHAR(20)  NOT NULL DEFAULT 'UPCOMING',
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_semesters_code        UNIQUE (code),
    CONSTRAINT fk_semesters_year        FOREIGN KEY (academic_year_id) REFERENCES academic_years (id) ON DELETE RESTRICT,
    CONSTRAINT ck_semesters_term_type   CHECK (term_type IN ('REGULAR', 'SUMMER')),
    CONSTRAINT ck_semesters_dates       CHECK (end_date > start_date),
    CONSTRAINT ck_semesters_credits     CHECK (min_credits >= 0 AND max_credits >= min_credits),
    CONSTRAINT ck_semesters_reg_window  CHECK (registration_end_at > registration_start_at),
    CONSTRAINT ck_semesters_status      CHECK (status IN ('UPCOMING', 'ONGOING', 'CLOSED'))
);

-- 21. Bảng classrooms (Phòng học)
CREATE TABLE classrooms (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code      VARCHAR(30) NOT NULL,
    building  VARCHAR(50) NOT NULL,
    capacity  INT         NOT NULL,
    room_type VARCHAR(20) NOT NULL DEFAULT 'THEORY',
    status    VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT uq_classrooms_code     UNIQUE (code),
    CONSTRAINT ck_classrooms_capacity CHECK (capacity > 0),
    CONSTRAINT ck_classrooms_type     CHECK (room_type IN ('THEORY', 'LAB', 'HALL')),
    CONSTRAINT ck_classrooms_status   CHECK (status IN ('ACTIVE', 'MAINTENANCE', 'INACTIVE'))
);

-- 22. Bảng course_sections (Lớp học phần)
CREATE TABLE course_sections (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_code     VARCHAR(40) NOT NULL,
    course_id        BIGINT      NOT NULL,
    semester_id      BIGINT      NOT NULL,
    group_number     INT         NOT NULL,
    lecturer_id      BIGINT      NULL,
    max_capacity     INT         NOT NULL DEFAULT 60,
    current_enrolled INT         NOT NULL DEFAULT 0,
    grade_status     VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    status           VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    published_at     TIMESTAMPTZ NULL,
    locked_at        TIMESTAMPTZ NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_course_sections_code  UNIQUE (section_code),
    CONSTRAINT uq_course_sections_group UNIQUE (course_id, semester_id, group_number),
    CONSTRAINT fk_sections_course       FOREIGN KEY (course_id)   REFERENCES courses (id)   ON DELETE RESTRICT,
    CONSTRAINT fk_sections_semester     FOREIGN KEY (semester_id) REFERENCES semesters (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sections_lecturer     FOREIGN KEY (lecturer_id) REFERENCES lecturers (id) ON DELETE SET NULL,
    CONSTRAINT ck_sections_group        CHECK (group_number >= 1),
    CONSTRAINT ck_sections_capacity     CHECK (max_capacity > 0 AND current_enrolled >= 0 AND current_enrolled <= max_capacity),
    CONSTRAINT ck_sections_grade_status CHECK (grade_status IN ('DRAFT', 'PUBLISHED', 'LOCKED')),
    CONSTRAINT ck_sections_status       CHECK (status IN ('OPEN', 'CLOSED', 'CANCELLED', 'COMPLETED'))
);

-- 23. Bảng section_schedules (Lịch học theo Thứ / Tiết / Tuần)
CREATE TABLE section_schedules (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id   BIGINT NOT NULL,
    day_of_week  INT    NOT NULL,
    start_period INT    NOT NULL,
    end_period   INT    NOT NULL,
    start_week   INT    NOT NULL DEFAULT 1,
    end_week     INT    NOT NULL DEFAULT 15,
    classroom_id BIGINT NOT NULL,
    CONSTRAINT fk_schedules_section   FOREIGN KEY (section_id)   REFERENCES course_sections (id) ON DELETE CASCADE,
    CONSTRAINT fk_schedules_classroom FOREIGN KEY (classroom_id) REFERENCES classrooms (id)      ON DELETE RESTRICT,
    CONSTRAINT ck_schedules_day       CHECK (day_of_week BETWEEN 2 AND 7),
    CONSTRAINT ck_schedules_period    CHECK (start_period BETWEEN 1 AND 12 AND end_period BETWEEN start_period AND 12),
    CONSTRAINT ck_schedules_week      CHECK (start_week >= 1 AND end_week BETWEEN start_week AND 25)
);

-- =============================================================================
-- PHẦN 6: PHÂN HỆ ĐĂNG KÝ HỌC PHẦN, ĐIỂM, THANG ĐIỂM & KIỂM TOÁN (5 BẢNG)
-- =============================================================================

-- 24. Bảng enrollments (Đăng ký học phần & Kết quả tổng kết)
CREATE TABLE enrollments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      BIGINT       NOT NULL,
    section_id      BIGINT       NOT NULL,
    course_id       BIGINT       NOT NULL,
    semester_id     BIGINT       NOT NULL,
    status          VARCHAR(20)  NOT NULL DEFAULT 'ENROLLED',
    attempt_number  INT          NOT NULL DEFAULT 1,
    enrolled_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    enrolled_by     BIGINT       NOT NULL,
    cancelled_at    TIMESTAMPTZ  NULL,
    cancelled_by    BIGINT       NULL,
    cancel_reason   TEXT         NULL,
    final_score_10  NUMERIC(4,1) NULL,
    letter_grade    VARCHAR(5)   NULL,
    gpa_score_4     NUMERIC(3,2) NULL,
    is_passed       BOOLEAN      NULL,
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_enrollments_student_section UNIQUE (student_id, section_id),
    CONSTRAINT fk_enrollments_student         FOREIGN KEY (student_id)   REFERENCES students (id)        ON DELETE RESTRICT,
    CONSTRAINT fk_enrollments_section         FOREIGN KEY (section_id)   REFERENCES course_sections (id) ON DELETE RESTRICT,
    CONSTRAINT fk_enrollments_course          FOREIGN KEY (course_id)    REFERENCES courses (id)         ON DELETE RESTRICT,
    CONSTRAINT fk_enrollments_semester        FOREIGN KEY (semester_id)  REFERENCES semesters (id)       ON DELETE RESTRICT,
    CONSTRAINT fk_enrollments_enrolled_by     FOREIGN KEY (enrolled_by)  REFERENCES users (id)           ON DELETE RESTRICT,
    CONSTRAINT fk_enrollments_cancelled_by    FOREIGN KEY (cancelled_by) REFERENCES users (id)           ON DELETE SET NULL,
    CONSTRAINT ck_enrollments_status          CHECK (status IN ('ENROLLED', 'CANCELLED')),
    CONSTRAINT ck_enrollments_attempt         CHECK (attempt_number >= 1),
    CONSTRAINT ck_enrollments_score_10        CHECK (final_score_10 IS NULL OR (final_score_10 BETWEEN 0.0 AND 10.0)),
    CONSTRAINT ck_enrollments_score_4         CHECK (gpa_score_4 IS NULL OR (gpa_score_4 BETWEEN 0.00 AND 4.00))
);

-- 25. Bảng student_grades (Điểm chi tiết từng Thành phần điểm)
CREATE TABLE student_grades (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id      BIGINT       NOT NULL,
    grade_component_id BIGINT       NOT NULL,
    score              NUMERIC(4,1) NOT NULL,
    updated_by         BIGINT       NOT NULL,
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_student_grades_pair       UNIQUE (enrollment_id, grade_component_id),
    CONSTRAINT fk_student_grades_enrollment FOREIGN KEY (enrollment_id)      REFERENCES enrollments (id)      ON DELETE CASCADE,

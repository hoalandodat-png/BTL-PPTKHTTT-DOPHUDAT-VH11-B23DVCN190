-- GIAI ĐOẠN 4 (MỤC 7.10): POSTGRESQL DDL SCHEMA, CONSTRAINTS, INDEXES & SEED DATA
-- DBMS: PostgreSQL 16/17+
-- Lưu ý: Toàn bộ 28 bảng khớp tuyệt đối 100% với ERD và Data Dictionary.
-- Dữ liệu mẫu bên dưới là dữ liệu giả lập (Mock Data) phục vụ phát triển & kiểm thử.

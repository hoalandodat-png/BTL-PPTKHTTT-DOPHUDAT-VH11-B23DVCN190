CREATE TABLE IF NOT EXISTS exam_schedules (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id      BIGINT      NOT NULL,
    classroom_id    BIGINT      NOT NULL,
    exam_date       DATE        NOT NULL,
    start_time      TIME        NOT NULL,
    end_time        TIME        NOT NULL,
    exam_format     VARCHAR(60) NOT NULL DEFAULT 'Thi viết / Tự luận',
    note            VARCHAR(255) NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_exam_section   FOREIGN KEY (section_id)   REFERENCES course_sections (id) ON DELETE CASCADE,
    CONSTRAINT fk_exam_classroom FOREIGN KEY (classroom_id) REFERENCES classrooms (id)      ON DELETE RESTRICT,
    CONSTRAINT ck_exam_time_range CHECK (end_time > start_time)
);

CREATE INDEX IF NOT EXISTS idx_exam_schedules_section ON exam_schedules (section_id);
CREATE INDEX IF NOT EXISTS idx_exam_schedules_date_room ON exam_schedules (exam_date, classroom_id);

